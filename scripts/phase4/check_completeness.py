"""Phase 4 — explicit completeness check of the evaluation matrix (all groups present).

Expected = evaluation plan x gaps x evaluation seeds, per condition and group.
Reports expected / actual / missing / duplicate / failed (a metric that must be
defined is NaN) / unexpected, calibration-seed leakage, manifest equality
across groups (both groups must see byte-identical instances) and latency rows.
Writes aggregated/completeness.json and tables/completeness.md.
"""

from __future__ import annotations

import argparse
import gzip
import json
import math
import sys
from collections import Counter
from pathlib import Path

from taorg.experiments.phase3.pipeline import read_csv_gz
from taorg.experiments.phase4 import pipeline as P


def _nan(x: str) -> bool:
    try:
        return math.isnan(float(x))
    except ValueError:
        return True


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", type=Path, default=Path("configs/experiments/phase4.yaml"))
    ap.add_argument("--out", type=Path, default=Path("results/phase4"))
    ap.add_argument("--groups", nargs="+", default=["baseline", "proposed"])
    a = ap.parse_args(argv)
    cfg, out = P.load_config(a.config), a.out
    sp = P.specs(cfg)
    seeds = list(cfg["seeds"]["evaluation"])
    result: dict = {"groups": {}}
    ok = True
    manifest_sha: dict[str, dict[str, str]] = {}
    lines = ["<!-- GENERATED by scripts/phase4/check_completeness.py -->\n", "# Phase 4 evaluation completeness\n",
             "| Group | Condition | Configs | Expected | Actual | Missing | Duplicate | Failed | Unexpected |",
             "|---|---|---|---|---|---|---|---|---|"]
    for g in a.groups:
        plan = json.loads((out / "configs" / f"evaluation_plan_{g}.json").read_text(encoding="utf-8"))
        rows = read_csv_gz(out / "raw" / f"evaluation_{g}.csv.gz")
        meta = json.loads((out / "raw" / f"stage_evaluate_{g}.json").read_text(encoding="utf-8"))
        keys = Counter((r["condition"], int(r["gap"]), int(r["seed"]), r["config_id"]) for r in rows)
        tot = Counter()
        per = {}
        for s in sp.values():
            exp = {(s.name, gap, seed, c) for gap in s.gaps for seed in seeds for c in plan[s.name]}
            act = {k for k in keys if k[0] == s.name}
            rs = [r for r in rows if r["condition"] == s.name]
            failed = [r for r in rs if _nan(r["churn_mean"]) or _nan(r["persistence_f1"])
                      or _nan(r["term_delay_mean"]) or _nan(r["method_runtime_s"])]
            rep = {"n_configs": len(plan[s.name]), "expected": len(exp), "actual": len(rs),
                   "missing": len(exp - act), "unexpected": len(act - exp),
                   "duplicates": sum(v - 1 for k, v in keys.items() if k[0] == s.name and v > 1),
                   "failed": len(failed)}
            per[s.name] = rep
            for k in ("expected", "actual", "missing", "unexpected", "duplicates", "failed"):
                tot[k] += rep[k]
            lines.append(f"| {g} | {s.name} | {rep['n_configs']} | {rep['expected']} | {rep['actual']} | "
                         f"{rep['missing']} | {rep['duplicates']} | {rep['failed']} | {rep['unexpected']} |")
        seen = sorted({int(r["seed"]) for r in rows})
        leak = sorted(set(seen) & set(cfg["seeds"]["calibration"]))
        with gzip.open(out / "raw" / f"manifests_evaluation_{g}.jsonl.gz", "rt", encoding="utf-8") as f:
            mans = [json.loads(x) for x in f]
        manifest_sha[g] = {m["instance_id"]: m["manifest_sha256"] for m in mans}
        exp_inst = sum(len(s.gaps) * len(seeds) for s in sp.values())
        lat = read_csv_gz(out / "raw" / f"latency_{g}.csv.gz")
        n_lat_methods = len({r["method"] for r in lat})
        lat_exp = len(sp["N0_clean"].gaps) * len(seeds) * n_lat_methods
        g_ok = (all(tot[k] == 0 for k in ("missing", "unexpected", "duplicates", "failed")) and not leak
                and seen == sorted(seeds) and len(mans) == exp_inst == len(manifest_sha[g])
                and meta.get("smoke") is False and len({r["run_id"] for r in rows}) == 1
                and len(lat) == lat_exp)
        ok &= g_ok
        result["groups"][g] = {"complete": g_ok, "totals": dict(tot), "per_condition": per,
                               "calibration_seed_leak": leak, "seeds_seen": seen,
                               "run_id": meta.get("run_id"), "git_commit": meta.get("git_commit"),
                               "git_dirty": meta.get("git_dirty"),
                               "manifests": {"expected": exp_inst, "actual": len(mans)},
                               "latency_rows": {"expected": lat_exp, "actual": len(lat)}}
        lines.append(f"| **{g} total** | | | {tot['expected']} | {tot['actual']} | {tot['missing']} | "
                     f"{tot['duplicates']} | {tot['failed']} | {tot['unexpected']} |")
    if len(manifest_sha) > 1:
        vals = list(manifest_sha.values())
        same = all(v == vals[0] for v in vals[1:])
        result["manifests_identical_across_groups"] = same
        ok &= same
    result["all_complete"] = ok
    (out / "aggregated").mkdir(parents=True, exist_ok=True)
    (out / "aggregated" / "completeness.json").write_text(json.dumps(result, indent=1), encoding="utf-8")
    lines.insert(2, f"Overall: **{'COMPLETE' if ok else 'INCOMPLETE'}**; manifests identical across groups: "
                    f"{result.get('manifests_identical_across_groups', 'n/a')}\n")
    (out / "tables").mkdir(parents=True, exist_ok=True)
    (out / "tables" / "completeness.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:3]))
    for g, r in result["groups"].items():
        print(g, r["totals"], "complete" if r["complete"] else "INCOMPLETE")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
