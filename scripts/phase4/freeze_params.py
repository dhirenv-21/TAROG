"""Phase 4 — verify a group's calibration and write its frozen-parameter artifact.

Run after ``--stage calibrate`` and ``--stage select`` for a group and BEFORE
``--stage evaluate`` for that group.  Reads calibration artifacts only.
Writes ``results/phase4/configs/frozen_<group>.json`` and
``results/phase4/tables/frozen_<group>.md``.  Exit status non-zero if any
check fails.

Usage:
    python scripts/phase4/freeze_params.py --group baseline
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import sys
from collections import Counter
from pathlib import Path

from taorg.experiments.phase3.pipeline import read_csv_gz
from taorg.experiments.phase3.selection import TIE_TOL
from taorg.experiments.phase4 import pipeline as P


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", type=Path, default=Path("configs/experiments/phase4.yaml"))
    ap.add_argument("--out", type=Path, default=Path("results/phase4"))
    ap.add_argument("--group", choices=("baseline", "proposed"), required=True)
    a = ap.parse_args(argv)
    cfg, out, g = P.load_config(a.config), a.out, a.group
    if (out / "raw" / f"evaluation_{g}.csv.gz").exists():
        print(f"ERROR: evaluation_{g} already exists; freezing must precede evaluation.")
        return 2
    meta = json.loads((out / "raw" / f"stage_calibrate_{g}.json").read_text(encoding="utf-8"))
    inst = json.loads((out / "raw" / f"calibration_instances_{g}.json").read_text(encoding="utf-8"))
    rows = [P._float_row(r) for r in read_csv_gz(out / "raw" / f"calibration_{g}.csv.gz")]
    sp = P.specs(cfg)
    cal, ev = set(cfg["seeds"]["calibration"]), set(cfg["seeds"]["evaluation"])
    expected = {f"{s.name}|g{gap}|s{seed}" for s in sp.values() if s.calibrate for gap in s.gaps for seed in cal}
    ids = [r["instance_id"] for r in inst]
    per_cond_inst = Counter(r["condition"] for r in inst)
    n_samples = int(cfg["search"]["n_samples"])
    exp_counts = {"no_memory": 1, "fixed_window": 40}
    cnt = Counter((r["condition"], r["method"]) for r in rows)
    count_ok = all(v == exp_counts.get(m, n_samples) for (c, m), v in cnt.items())
    methods_ok = all({m for (c, m) in cnt if c == s.name} == set(P.methods_for(cfg, g, s.name))
                     for s in sp.values() if s.calibrate)
    checks = {
        "stage_not_smoke": meta.get("smoke") is False,
        "full_sample_budget": meta.get("max_samples") is None,
        "config_sha_matches": meta.get("config_sha256") == cfg["_sha256"],
        "instances_exact_match": set(ids) == expected and len(ids) == len(expected),
        "only_calibration_seeds": {r["seed"] for r in inst} <= cal,
        "no_evaluation_seeds": not ({r["seed"] for r in inst} & ev),
        "config_counts_equal_budget": count_ok,
        "methods_as_registered": methods_ok,
        "every_config_saw_every_instance": all(int(r["n_instances"]) == per_cond_inst[r["condition"]] for r in rows),
        "no_nan_f1_or_delay": all(not math.isnan(r["persistence_f1"]) and not math.isnan(r["term_delay_mean"])
                                  for r in rows),
    }
    ok = all(checks.values())
    selected = json.loads((out / "configs" / f"selected_{g}.json").read_text(encoding="utf-8"))
    pareto = json.loads((out / "configs" / f"pareto_{g}.json").read_text(encoding="utf-8"))
    by = {(r["condition"], r["config_id"]): r for r in rows}
    frozen = {}
    lines = [f"<!-- GENERATED by scripts/phase4/freeze_params.py --group {g} -->\n",
             f"# Phase 4 frozen parameters — group `{g}` (calibration seeds 3000–3019 only)\n",
             "Rule: max mean calibration Persistence F1 subject to mean delay <= B; ties by churn, "
             "delay, false persistence, sample index (Phase 3 rule).\n",
             "| Condition | Method | B | Calib F1 | Calib delay | Churn | Feasible | Ties | Params |",
             "|---|---|---|---|---|---|---|---|---|"]
    for cond, by_m in selected.items():
        for name, by_b in by_m.items():
            for b, sel in by_b.items():
                r = by[(cond, sel["config_id"])]
                feas = [x for x in rows if x["condition"] == cond and x["method"] == sel["method"]
                        and x["term_delay_mean"] <= float(b)]
                ties = sum(1 for x in feas if x["persistence_f1"] >= r["persistence_f1"] - TIE_TOL) if sel["feasible"] else 0
                frozen.setdefault(cond, {}).setdefault(name, {})[b] = {
                    "config_id": sel["config_id"], "params": sel["params"], "feasible": sel["feasible"],
                    "n_feasible": sel["n_feasible"], "n_tied_at_best_f1": ties,
                    "calib_persistence_f1": r["persistence_f1"], "calib_term_delay_mean": r["term_delay_mean"],
                    "calib_churn_mean": r["churn_mean"], "calib_false_pers_mean": r["false_pers_mean"]}
                if b == str(cfg["primary_budget_frames"]):
                    lines.append(f"| {cond} | {name} | {b} | {r['persistence_f1']:.4f} | {r['term_delay_mean']:.2f} | "
                                 f"{r['churn_mean']:.4f} | {sel['feasible']} ({sel['n_feasible']}) | {ties} | "
                                 f"`{json.dumps({k: round(v, 4) if isinstance(v, float) else v for k, v in sel['params'].items()}, sort_keys=True)}` |")
    art = {"description": f"Phase 4 frozen parameters, group {g} (calibration seeds only).",
           "registration_commit": "bad0ef9", "config_sha256": cfg["_sha256"],
           "calibration_run_id": meta.get("run_id"), "calibration_git_commit": meta.get("git_commit"),
           "calibration_git_dirty": meta.get("git_dirty"),
           "checks": checks, "all_passed": ok, "expected_instances": len(expected), "actual_instances": len(ids),
           "artifact_sha256": {f"raw/calibration_{g}.csv.gz": sha256(out / "raw" / f"calibration_{g}.csv.gz"),
                               f"configs/selected_{g}.json": sha256(out / "configs" / f"selected_{g}.json"),
                               f"configs/pareto_{g}.json": sha256(out / "configs" / f"pareto_{g}.json"),
                               "configs/context.json": sha256(out / "configs" / "context.json")},
           "pareto_set_sizes": {c: {fk: {m: len(v) for m, v in d.items()} for fk, d in fr.items()}
                                for c, fr in pareto.items()},
           "frozen": frozen}
    (out / "configs" / f"frozen_{g}.json").write_text(json.dumps(art, indent=1), encoding="utf-8")
    (out / "tables").mkdir(parents=True, exist_ok=True)
    (out / "tables" / f"frozen_{g}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(checks, indent=1))
    print("calibration verification:", "PASS" if ok else "FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
