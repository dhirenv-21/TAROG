"""Phase 5H Stage 0 — tables and figures from saved artifacts only (results/phase5h/stage0/)."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from taorg.experiments.phase3.plots import _setup  # noqa: E402

OUT = Path("results/phase5h/stage0")


def main() -> None:
    _setup()
    s = json.loads((OUT / "summary.json").read_text(encoding="utf-8"))
    P = np.load(OUT / "params.npz")
    vocab = s["vocab"]
    R = len(vocab)
    K = 2 * R
    beta2 = float(P["beta2"])

    # Fig 1: HK2 cross-excitation branching ratios alpha/beta (FIT fit), targets x sources.
    A = P["HK2_A"][:, :K] / beta2
    order = np.argsort([-(r["onsets"] + r["offsets"]) for r in s["descriptive"]["per_predicate"]])
    keep = order[:20]
    idx = np.array([2 * r + o for r in keep for o in (0, 1)])
    lab = [f"{'ON' if o == 0 else 'OFF'} {vocab[r]}" for r in keep for o in (0, 1)]
    fig, ax = plt.subplots(figsize=(10, 9))
    im = ax.imshow(A[np.ix_(idx, idx)], cmap="viridis", vmin=0, vmax=np.quantile(A[np.ix_(idx, idx)], 0.99))
    ax.set_xticks(range(len(lab)))
    ax.set_xticklabels(lab, rotation=90, fontsize=5.5)
    ax.set_yticks(range(len(lab)))
    ax.set_yticklabels(lab, fontsize=5.5)
    ax.set_xlabel("source event type (history)")
    ax.set_ylabel("target event type (intensity)")
    fig.colorbar(im, ax=ax, label="branching ratio α/β (HK2, FIT)")
    ax.set_title(f"HK2 excitation among the 20 most frequent predicates (β = {beta2:g} s⁻¹)", fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / "fig1_hk2_branching.png", dpi=200)
    fig.savefig(OUT / "fig1_hk2_branching.pdf")
    plt.close(fig)

    # Fig 2: C1 null distribution vs observed G_cross.
    g = s["test"]["G_cross"]
    fig, ax = plt.subplots(figsize=(5, 2.6))
    ax.hist(s["c1_null"], bins=12, color="#999999", label="circular-shift null (19)")
    ax.axvline(g["mean"], color="#D55E00", label=f"observed {g['mean']:.4f}")
    ax.axvspan(g["ci_lo"], g["ci_hi"], color="#D55E00", alpha=0.2)
    ax.set_xlabel("ΔLL per TEST event, HK2 − HK1 (nats)")
    ax.legend(frameon=False, fontsize=6)
    fig.tight_layout()
    fig.savefig(OUT / "fig2_c1_null.png", dpi=200)
    fig.savefig(OUT / "fig2_c1_null.pdf")
    plt.close(fig)

    t = s["test"]
    d = s["decision"]
    c4 = s["c4"]
    L = ["<!-- GENERATED by scripts/phase5h/report_stage0.py -->\n", "# Phase 5H Stage 0 results tables\n",
         f"TEST videos {s['n_test']}, TEST events {t['n_events']}; FIT {s['n_fit']}, DEV {s['n_dev']}.\n",
         "## Held-out log-likelihood per event (nats)\n", "| Model | LL/event |", "|---|---|"]
    L += [f"| {m} | {v:.4f} |" for m, v in t["ll_per_event"].items()]
    L += ["\n## Differences (per TEST event, 95% video bootstrap CI)\n", "| Quantity | mean [CI] |", "|---|---|"]
    for k in ("G_cross", "G_self", "G_dur", "G_base", "HK1_minus_DUR"):
        x = t[k]
        L.append(f"| {k} | {x['mean']:+.4f} [{x['ci_lo']:+.4f}, {x['ci_hi']:+.4f}] |")
    L += ["\n## Selection (DEV)\n", f"`{json.dumps(s['selected'])}`\n",
          "## C1 null (19 circular shifts)\n", f"null max {d['null_max']:.5f}, median {d['null_median']:.5f}, "
          f"permutation p = {d['perm_p']:.3f}\n", f"values: {', '.join(f'{v:.5f}' for v in s['c1_null'])}\n",
          "## C4 stability\n", f"S_real = {c4['S_real']}, S_null = {c4['S_null']}; "
          f"ρ̄_real = {c4['rho_real']:.3f}, ρ̄_null = {[round(r, 3) for r in c4['rho_null']]}\n",
          "## Decision\n", f"C1 {d['C1']} · C2 {d['C2']} · C3 {d['C3']} (excess/G_self = {d['excess_over_self']:.3f}) · "
          f"C4 {d['C4']} → **HAWKES SIGNAL = {d['label']}**\n",
          f"C3 at descriptive ratios: {d['c3_descriptive']}\n",
          "## Top-25 cross cells (HK2 FIT; branching α/β; folds present of 5)\n",
          "| Target | Source | α | α/β | folds |", "|---|---|---|---|---|"]
    L += [f"| {c['target']} | {c['source']} | {c['alpha']:.4f} | {c['branching']:.3f} | {c['folds_present']} |"
          for c in s["top_cross_cells"]]
    L += ["\n## Descriptive: peri-event onset rates (FIT; onsets of target per source event, by lag bin)\n",
          "| Source → target | n source | observed by lag [0-.5,.5-1,1-2,2-5,5-10 s] | baseline (HK0 μ × bin) |",
          "|---|---|---|---|"]
    L += [f"| {e['source']} → {e['target']} | {e['n_source_events']} | {e['onsets_per_source_event_by_lag']} | "
          f"{e.get('baseline_onsets_per_source_event_by_lag')} |" for e in s["descriptive"]["peri_event_top20"]]
    (OUT / "stage0_tables.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written")


if __name__ == "__main__":
    main()
