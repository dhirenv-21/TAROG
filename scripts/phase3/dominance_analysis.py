"""Phase 3 — exploratory formal Pareto-dominance analysis (NOT part of the H1 rule).

Reads ``raw/evaluation_runs.csv.gz`` and ``configs/pareto_sets.json``; writes
``aggregated/dominance.json`` and ``tables/dominance.md``.  Definitions are in
``taorg.experiments.phase3.dominance`` (committed before evaluation data existed).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

from taorg.experiments.phase3.analysis import EvalIndex, load_eval
from taorg.experiments.phase3.conditions import derive_seed
from taorg.experiments.phase3.dominance import bootstrap_dominance, classify, set_dominates
from taorg.experiments.phase3.pipeline import condition_specs, load_phase3_config


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--config", type=Path, default=Path("configs/experiments/phase3_pilot.yaml"))
    ap.add_argument("--out", type=Path, default=Path("results/phase3"))
    args = ap.parse_args(argv)
    cfg = load_phase3_config(args.config)
    out = args.out
    specs = condition_specs(cfg)
    crit, st = cfg["h1_criteria"], cfg["statistics"]
    treat, comps = crit["treatment"], list(crit["comparators"])
    ref = float(st["hv_delay_ref"])
    R = int(st["hv_bootstrap_resamples"])
    df = load_eval(out)
    seeds = sorted(df.seed.unique().tolist())
    ix = EvalIndex(df, seeds)
    pareto = json.loads((out / "configs" / "pareto_sets.json").read_text(encoding="utf-8"))
    h1 = [s.name for s in specs.values() if s.role in ("h1_primary", "h1_robustness")]

    def mats(cond: str, gap: int, method: str) -> tuple[np.ndarray, np.ndarray]:
        cids = [it["config_id"] for it in pareto[cond][method]]
        F = np.vstack([ix.values(cond, gap, c, "persistence_f1") for c in cids])
        D = np.vstack([ix.values(cond, gap, c, "term_delay_mean") for c in cids])
        return F, D

    results: dict[tuple[str, int], dict] = {}
    rows = []
    for cond in h1:
        for gap in specs[cond].gaps:
            rng = np.random.default_rng(derive_seed(cfg["seeds"]["bootstrap"], "dominance", cond, gap))
            idx = rng.integers(0, len(seeds), size=(R, len(seeds)))
            Fg, Dg = mats(cond, gap, treat)
            g_pts = list(zip(np.nanmean(Fg, axis=1), np.nanmean(Dg, axis=1)))
            res = {}
            for m in [*comps, "no_memory"]:
                Fm, Dm = mats(cond, gap, m)
                m_pts = list(zip(np.nanmean(Fm, axis=1), np.nanmean(Dm, axis=1)))
                dom = set_dominates(g_pts, m_pts, ref)
                rev = set_dominates(m_pts, g_pts, ref)
                p = bootstrap_dominance(Fg, Dg, Fm, Dm, idx, ref)
                p_rev = bootstrap_dominance(Fm, Dm, Fg, Dg, idx, ref)
                res[m] = {"dominates": bool(dom), "p_dom": p, "dominated_by": bool(rev), "p_dominated_by": p_rev}
                rows.append({"condition": cond, "gap": gap, "comparator": m, **res[m]})
            results[(cond, gap)] = res
    overall = classify(results, comps)
    per_cond = {c: classify({k: v for k, v in results.items() if k[0] == c}, comps) for c in h1}
    payload = {"definition_module": "taorg.experiments.phase3.dominance", "cost_ref": ref,
               "bootstrap_resamples": R, "treatment": treat, "comparators": comps,
               "classification_overall": overall, "classification_per_condition": per_cond,
               "rows": rows}
    (out / "aggregated").mkdir(parents=True, exist_ok=True)
    (out / "aggregated" / "dominance.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")

    labels = cfg["method_labels"]
    lines = ["<!-- GENERATED by scripts/phase3/dominance_analysis.py — do not edit by hand. -->\n",
             "# Frontier set dominance (EXPLORATORY; not part of the H1 rule)\n",
             f"Vis-Gated EMA frontier vs comparator frontier, evaluation-seed means, box delay < {ref:g} "
             f"frames. p_dom = share of {R} paired bootstrap resamples in which dominance holds.\n",
             f"**Overall classification: {overall}** (A = Pareto-dominates everywhere, B = condition-"
             f"specific, C = no advantage). Per condition: "
             + ", ".join(f"{c}: {v}" for c, v in per_cond.items()) + "\n",
             "| Condition | Gap | Comparator | Gated >> comp | p_dom | comp >> Gated | p (reverse) |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['condition']} | {r['gap']} | {labels[r['comparator']]} | {r['dominates']} | "
                     f"{r['p_dom']:.3f} | {r['dominated_by']} | {r['p_dominated_by']:.3f} |")
    (out / "tables" / "dominance.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"classification overall={overall} per_condition={per_cond}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
