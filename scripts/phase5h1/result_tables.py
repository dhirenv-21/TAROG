"""Render Phase 5H-1 result tables (Markdown) from results/phase5h1/full/analysis.json + completeness.json.

Every number in research/phase5h1_exit_report.md is copied from these generated tables.

Usage:
    python scripts/phase5h1/result_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

OUT = Path("results/phase5h1/full")


def f(x, n=4):
    return "—" if x is None else (f"{x:+.{n}f}" if isinstance(x, float) else str(x))


def ci(s, n=4):
    return f"{s['mean']:+.{n}f} [{s['ci_lo']:+.{n}f}, {s['ci_hi']:+.{n}f}]"


def main() -> None:
    a = json.loads((OUT / "analysis.json").read_text(encoding="utf-8"))
    cp = json.loads((OUT / "completeness.json").read_text(encoding="utf-8"))
    L = ["# Phase 5H-1 generated result tables", "",
         f"Source: `results/phase5h1/full/analysis.json` (frozen commit `{a['frozen_commit'][:7]}`, code hash "
         f"`{a['code_hash']}`). EXPLORATORY evidence class. Generated by `scripts/phase5h1/result_tables.py`.", ""]

    s = a["sample"]
    L += ["## T1. Sample sizes", "", "| split | videos | modelled events |", "|---|---:|---:|",
          f"| TRAIN | {s['n_videos']['TRAIN']} | — |", f"| SELECT | {s['n_videos']['SELECT']} | — |",
          f"| EVAL-A | {s['n_videos']['EVAL_A']} | {int(s['eval_events_A']):,} |",
          f"| EVAL-B | {s['n_videos']['EVAL_B']} | {int(s['eval_events_B']):,} |",
          f"| EVAL (A∪B) | {s['n_videos']['EVAL_A'] + s['n_videos']['EVAL_B']} | {int(s['eval_events']):,} |", "",
          f"Modelled target types: {s['n_targets']}.", "",
          "| family | target types | EVAL events | share |", "|---|---:|---:|---:|"]
    for F, n in sorted(s["family_events"].items(), key=lambda kv: -kv[1]):
        L.append(f"| {F} | {a['families'][F]['n_targets'] if F in a['families'] else 0} | {int(n):,} | "
                 f"{100 * n / s['eval_events']:.1f}% |")
    pt = sorted(s["per_target"], key=lambda r: -(r["eval_events_A"] + r["eval_events_B"]))
    L += ["", "Least-supported target types on EVAL (A+B): " + ", ".join(
        f"{r['type']} {int(r['eval_events_A'] + r['eval_events_B'])}" for r in pt[-8:]), ""]

    L += ["## T2. Held-out log-likelihood per EVAL event (nats)", "", "| model | EVAL | EVAL-A | EVAL-B |",
          "|---|---:|---:|---:|"]
    for r in ["G0", "G1", "G2", "G3", "G4x", "G4", "G4+"]:
        L.append(f"| {r} | {a['ll_per_event']['EVAL'][r]:.4f} | {a['ll_per_event']['EVAL_A'][r]:.4f} | "
                 f"{a['ll_per_event']['EVAL_B'][r]:.4f} |")
    L += ["", "## T3. Paired differences (nats/event, 95% video-bootstrap CI, 2000 resamples)", "",
          "| comparison | EVAL | EVAL-A | EVAL-B | videos with Δ>0 (EVAL) |", "|---|---|---|---|---:|"]
    for k, v in a["comparisons"].items():
        L.append(f"| {k} | {ci(v['EVAL'])} | {ci(v['EVAL_A'])} | {ci(v['EVAL_B'])} | "
                 f"{100 * v['EVAL']['frac_videos_positive']:.1f}% |")
    g21 = a["comparisons"]["G2-G1"]["EVAL"]["mean"]
    L += ["", f"Effect-size scale: Δ(G2, G1) duration gain = {g21:+.4f}. "
          f"Δ(G4, G3) / Δ(G2, G1) = {a['comparisons']['G4-G3']['EVAL']['mean'] / g21:.3f}; "
          f"Δ(G4x, G2) / Δ(G2, G1) = {a['comparisons']['G4x-G2']['EVAL']['mean'] / g21:.3f}.", ""]

    d = a["decision"]
    L += ["## T4. Null comparisons (38 replicates; refit at frozen ridge)", "",
          "| quantity | observed | N-circ max | N-jit max | combined max | combined median |", "|---|---:|---:|---:|---:|---:|",
          f"| Δ(G4x, G2) | {a['comparisons']['G4x-G2']['EVAL']['mean']:+.4f} | {d['null_circ_cross_max']:+.4f} | "
          f"{d['null_jit_cross_max']:+.4f} | {d['null_cross_max']:+.4f} | {d['null_cross_med']:+.4f} |",
          f"| Δ(G4, G3) | {a['comparisons']['G4-G3']['EVAL']['mean']:+.4f} | {d['null_circ_time_max']:+.4f} | "
          f"{d['null_jit_time_max']:+.4f} | {d['null_time_max']:+.4f} | {d['null_time_med']:+.4f} |", ""]
    reps = a["nulls"]["replicates"]
    obs_ev = s["eval_events"]
    for kind in ("circ", "jit"):
        evs = [r["n_events"] for r in reps if r["kind"] == kind]
        L.append(f"- {kind}: null-EVAL event counts {int(min(evs)):,}–{int(max(evs)):,} vs observed {int(obs_ev):,}; "
                 f"non-converged null fits {sum(r['non_converged'] for r in reps if r['kind'] == kind)}.")
    L += ["", "## T5. Registered decision (`decide_phase5h1`)", "", "| criterion | definition | value | pass |",
          "|---|---|---|:-:|",
          f"| K1 | CI_lo Δ(G4x,G2) > 0 and Δ > null max | CI_lo {a['comparisons']['G4x-G2']['EVAL']['ci_lo']:+.4f}; "
          f"Δ {a['comparisons']['G4x-G2']['EVAL']['mean']:+.4f} vs {d['null_cross_max']:+.4f} | {'✔' if d['K1'] else '✘'} |",
          f"| K2 | CI_lo Δ(G4,G3) > 0 and Δ > null max | CI_lo {a['comparisons']['G4-G3']['EVAL']['ci_lo']:+.4f}; "
          f"Δ {a['comparisons']['G4-G3']['EVAL']['mean']:+.4f} vs {d['null_time_max']:+.4f} | {'✔' if d['K2'] else '✘'} |",
          f"| K3 | Δ(G4,G3) − null med ≥ 0.10·Δ(G2,G1) | {d['time_excess']:+.4f} vs {d['k3_threshold']:+.4f} | "
          f"{'✔' if d['K3'] else '✘'} |",
          f"| K4 | ≥1 discovery at FDR ≤ 0.10 and ρ_real > max ρ_null | {a['stability']['n_discoveries']} discoveries "
          f"(τ = {f(a['stability']['tau'], 2)}); ρ {a['stability']['rho_real']:.3f} vs max {max(a['stability']['rho_null']):.3f} | "
          f"{'✔' if d['K4'] else '✘'} |",
          f"| family test | see T6 | passing: {', '.join(d['families_passing']) or 'none'} | — |", "",
          f"Null maxima by null type — Δ(G4x,G2): N-circ {d['null_circ_cross_max']:+.4f}, N-jit {d['null_jit_cross_max']:+.4f}; "
          f"Δ(G4,G3): N-circ {d['null_circ_time_max']:+.4f}, N-jit {d['null_jit_time_max']:+.4f}.", "",
          f"**HAWKES TRACK = {d['label']}**", ""]
    L += ["## T6. Family test (Δ_F(G4, G3); nats per family event)", "",
          "| family | EVAL-A | EVAL-B | EVAL | null max | null med | 10%·Δ_F(G2,G1) | Δ_F(G4x,G2) | pass |",
          "|---|---|---|---|---:|---:|---:|---|:-:|"]
    for F, v in sorted(a["families"].items(), key=lambda kv: -kv[1]["d_all"]["n_events"]):
        L.append(f"| {F} | {ci(v['d_a'])} | {ci(v['d_b'])} | {ci(v['d_all'], 5)} | {v['null_max']:+.5f} | "
                 f"{v['null_med']:+.5f} | {0.1 * v['dur_gain']:+.4f} | {ci(v['cross_all'])} | {'✔' if v['passes'] else '✘'} |")
    st = a["stability"]
    L += ["", "## T7. Fold reproducibility (G4 on 5 TRAIN folds; 5 N-jit fold-null replicates)", "",
          f"- HIST cells: {st['n_cells']}; 5/5 sign agreement: real {st['n_sign_agree_real']}, "
          f"N-jit {st['n_sign_agree_null']}.",
          f"- τ = {f(st['tau'], 3)}; estimated FDR at τ = {f(st['fdr_at_tau'], 3)}; minimum FDR over the scan = "
          f"{f(st['fdr_scan_min'], 3)}; discoveries = {st['n_discoveries']}.",
          f"- Inter-fold Spearman (mean of 10 fold pairs): real {st['rho_real']:.3f}; N-jit "
          f"{', '.join(f'{x:.3f}' for x in st['rho_null'])}.",
          f"- Discoveries by family: {st['discoveries_by_family']}; by class: {st['discoveries_by_class']}.", ""]
    if st["discoveries"]:
        L += ["| target | source | lag (s) | mean w | SD | t | support (source events) |", "|---|---|---|---:|---:|---:|---:|"]
        for x in sorted(st["discoveries"], key=lambda x: -abs(x["t"]))[:25]:
            L.append(f"| {x['target']} | {x['source']} | {x['lag_bin']} | {x['mean_w']:+.3f} | {x['sd_w']:.3f} | "
                     f"{x['t']:+.1f} | {int(x['support_source_events']):,} |")
        L.append("")
    L += ["## T8. RQ-H2 ablations: Δ(G3 + one HIST block, G3), nats/event", "", "| block | EVAL | EVAL-A | EVAL-B |",
          "|---|---|---|---|"]
    for k, v in a["ablations"].items():
        L.append(f"| {k} | {ci(v['EVAL'])} | {ci(v['EVAL_A'])} | {ci(v['EVAL_B'])} |")
    L += ["", "## T9. Stage-0-generated hypotheses on EVAL (model-free; window (0, 2] s)", "",
          "| H | source onset → target offset | E_in | X_in (s) | RR [95% CI] | perm p | Holm p | status |",
          "|---|---|---:|---:|---|---:|---:|---|"]
    import math
    for r in a["hypotheses"]["results"]:
        rr = "—" if r["rr"] is None else (f"{r['rr']:.2f} [{math.exp(r['ci_lo']):.2f}, {math.exp(r['ci_hi']):.2f}]"
                                          if r["ci_lo"] is not None and not r["underpowered"]
                                          else f"{r['rr']:.2f} (CI not meaningful: {int(r['E_in'])} event(s))")
        L.append(f"| {r['hypothesis']} | ON({r['source_onset']}) → OFF({r['target_offset']}) | {int(r['E_in'])} | "
                 f"{r['X_in_s']:.0f} | {rr} | {r['p_perm']:.3f} | {r.get('p_holm', float('nan')):.3f} | "
                 f"{'UNDERPOWERED' if r['underpowered'] else ('replicates' if r.get('significant_holm_0.05') else 'not significant')} |")
    ne = a["next_event"]
    L += ["", "## T10. Next-event type (secondary, descriptive)", "", "| model | log-loss | top-1 |", "|---|---:|---:|"]
    for r, v in ne["per_rung"].items():
        L.append(f"| {r} | {v['logloss']:.4f} | {v['top1']:.4f} |")
    L += ["", f"- log-loss G4 − G3: {ci(ne['logloss_G4_minus_G3'])}; top-1 G4 − G3: {ci(ne['top1_G4_minus_G3'])} "
          f"(negative log-loss difference = better).", ""]
    c = a["costs"]
    L += ["## T11. Runtime and memory (registered run; job wall time inside workers)", "",
          "| job type | jobs | summed job time (h) | max peak RSS (GB) | failed |", "|---|---:|---:|---:|---:|"]
    for k, v in sorted(c["by_job_type"].items()):
        L.append(f"| {k} | {v['jobs']} | {v['cpu_s'] / 3600:.2f} | {v['max_peak_rss_gb']:.2f} | {v['failed']} |")
    L += ["", f"Total summed job time {c['total_job_cpu_h']:.1f} h (includes the superseded max_iter = 500 attempt and "
          "the ~34-min system pause; see exit report).", ""]
    L += ["## T12. Experiment matrix (expected / complete / missing)", "", "| stage | expected | unique | complete | missing | "
          "non-converged | unexpected checkpoints |", "|---|---:|---:|---:|---:|---:|---:|"]
    for k, v in cp.items():
        if isinstance(v, dict) and "expected" in v:
            L.append(f"| {k} | {v['expected']} | {v['unique_expected']} | {v['complete']} | {v['missing']} | "
                     f"{v['non_converged_or_nonfinite']} | {v['unexpected_checkpoints']} |")
    L += ["", f"Failed job attempts: {len(cp['attempts']['failed'])}; blocked: {len(cp['attempts']['blocked'])}; "
          f"all complete: {cp['all_complete']}.", ""]
    (OUT / "tables.md").write_text("\n".join(L), encoding="utf-8")
    print("written", OUT / "tables.md")


if __name__ == "__main__":
    main()
