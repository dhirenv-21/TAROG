"""Phase 4 markdown tables (reporting only; no decision logic)."""

from __future__ import annotations

import math
from pathlib import Path
from typing import Any

import pandas as pd

HDR = "<!-- GENERATED by taorg.experiments.phase4 from results/phase4 artifacts — do not edit by hand. -->\n"


def _f(v: Any, d: int = 3) -> str:
    try:
        v = float(v)
    except (TypeError, ValueError):
        return "—"
    return "—" if math.isnan(v) else f"{v:.{d}f}"


def _ci(m: Any, lo: Any, hi: Any, d: int = 3) -> str:
    return f"{_f(m, d)} [{_f(lo, d)}, {_f(hi, d)}]"


def _lab(cfg: dict, m: str) -> str:
    base, _, suf = m.partition("__")
    return cfg["method_labels"].get(base, base) + (" (half-sample control)" if suf else "")


def write_tables(cfg: dict[str, Any], out: Path, desc: pd.DataFrame, hv: pd.DataFrame, diffs: pd.DataFrame,
                 ops: pd.DataFrame, result: dict[str, Any], cells: dict[str, Any]) -> None:
    """Write all Phase 4 tables."""
    T = out / "tables"
    T.mkdir(parents=True, exist_ok=True)
    order = list(cfg["method_labels"])

    # Operating points (primary budget)
    lines = [HDR, f"# Operating points (budget {cfg['primary_budget_frames']} frames, tuned on each condition's "
             "tuning source; mean [95% t-CI], n = 30)\n"]
    B = str(cfg["primary_budget_frames"])
    if not desc.empty:
        for cond, dc in desc[desc.budget == B].groupby("condition", sort=False):
            lines += [f"\n## {cond}\n", "| Gap | Method | F1 | Delay (fr) | Delay (s) | FPR | Churn | Swap recall | Ghost frames |",
                      "|---|---|---|---|---|---|---|---|---|"]
            dc = dc.assign(_o=dc.method.map(lambda m: (order.index(m.split("__")[0]) if m.split("__")[0] in order else 99, m)))
            for _, r in dc.sort_values(["gap", "_o"]).iterrows():
                lines.append(f"| {r.gap} | {_lab(cfg, r.method)} | "
                             + " | ".join(_ci(r[f"{m}__mean"], r[f"{m}__ci_lo"], r[f"{m}__ci_hi"], d)
                                          for m, d in (("persistence_f1", 3), ("term_delay_mean", 2), ("delay_s", 3),
                                                       ("false_pers_mean", 3), ("churn_mean", 4),
                                                       ("diag_swap_recall", 3), ("diag_ghost_edge_frames", 1)))
                             + " |")
    (T / "operating_points.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Hypervolumes
    lines = [HDR, "# Frontier hypervolume (evaluation seeds, 95% paired-bootstrap CI)\n",
             "Default frontier: F1 vs termination delay, box delay [1, 40] frames. Identity frontier (F5, F8): "
             "swap recall vs ghost edge-frames, box [0, 300].\n"]
    if not hv.empty:
        for (cond, fk), dc in hv.groupby(["condition", "frontier"], sort=False):
            gaps = sorted(dc.gap.unique())
            lines += [f"\n## {cond} — {fk}\n", "| Method | " + " | ".join(f"gap {g}" for g in gaps) + " |",
                      "|---|" + "---|" * len(gaps)]
            for m in sorted(dc.method.unique(), key=lambda m: (order.index(m.split("__")[0]) if m.split("__")[0] in order else 99, m)):
                cells_ = []
                for g in gaps:
                    r = dc[(dc.method == m) & (dc.gap == g)]
                    cells_.append(_ci(r.hv.iloc[0], r.ci_lo.iloc[0], r.ci_hi.iloc[0]) if len(r) else "—")
                lines.append(f"| {_lab(cfg, m)} | " + " | ".join(cells_) + " |")
    (T / "hypervolume.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Decisions
    dec = result.get("decisions", {})
    for name in ("H2", "H2_tuning_control", "H3", "H4"):
        if name not in dec:
            continue
        d = dec[name]
        lines = [HDR, f"# {name}: **{d['decision']}**\n", "| Quantity | Value |", "|---|---|"]
        lines += [f"| {k} | {v} |" for k, v in d.items() if k != "decision"]
        lines += ["\n## Cells\n"]
        if name.startswith("H4"):
            lines += ["| Cell | Outcome | vs GatedEMA | vs VA-HMM |", "|---|---|---|---|"]
            for cell, v in cells[name].items():
                pc = v["per_comparator"]
                lines.append(f"| {cell} | {v['outcome']} | "
                             + " | ".join(f"win={pc[m]['win']} ({pc[m]['win_kind']}), loss={pc[m]['loss']} ({pc[m]['loss_kind']})"
                                          for m in pc) + " |")
        else:
            comps = list(next(iter(cells[name].values()))["per_comparator"]) if cells[name] else []
            lines += ["| Cell | Outcome | " + " | ".join(f"ΔHV vs {_lab(cfg, m)} [CI]; failed checks" for m in comps) + " |",
                      "|---|---|" + "---|" * len(comps)]
            for cell, v in cells[name].items():
                parts = []
                for m in comps:
                    r = v["per_comparator"][m]
                    dh = r.get("d_hv") or {}
                    parts.append(f"{_ci(dh.get('mean_diff'), dh.get('ci_lo'), dh.get('ci_hi'))}; "
                                 f"{','.join(r.get('failed_checks', [])) or '—'}")
                lines.append(f"| {cell} | {v['outcome']} | " + " | ".join(parts) + " |")
        (T / f"{name.lower()}.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # Ablation
    lines = [HDR, "# Ablation ladder: ΔHV (treatment − comparator) on each condition's registered frontier\n"]
    if not diffs.empty:
        ab = diffs[diffs.comparison.str.match(r"^A\d$")]
        for tag, dc in ab.groupby("comparison"):
            t, c = dc.treatment.iloc[0], dc.comparator.iloc[0]
            lines += [f"\n## {tag}: {_lab(cfg, t)} vs {_lab(cfg, c)}\n", "| Condition | Frontier | " +
                      " | ".join(f"gap {g}" for g in sorted(dc.gap.unique())) + " |",
                      "|---|---|" + "---|" * dc.gap.nunique()]
            for (cond, fk), dd in dc.groupby(["condition", "frontier"], sort=False):
                row = []
                for g in sorted(dc.gap.unique()):
                    r = dd[dd.gap == g]
                    row.append(_ci(r.mean_diff.iloc[0], r.ci_lo.iloc[0], r.ci_hi.iloc[0]) if len(r) else "—")
                lines.append(f"| {cond} | {fk} | " + " | ".join(row) + " |")
    ret = result.get("ablation_retention", {})
    if ret:
        lines += ["\n## Mechanism retention (pre-registered rule)\n", "| Rung | Retained | Target gains / cells | NI losses |",
                  "|---|---|---|---|"]
        for m, r in ret.items():
            lines.append(f"| {_lab(cfg, m)} | {r['retained']} | {r['n_target_gains']} / {r['n_target_cells']} | {r['n_ni_losses']} |")
    (T / "ablation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # H4 detail (paired operating points)
    if not ops.empty and (ops.family == "H4").any():
        h = ops[ops.family == "H4"]
        lines = [HDR, "# H4 paired operating-point differences (M5 − comparator), budget 5, tuned on SC only\n",
                 "Delay in seconds. d_z 'undef' when SD of paired differences < 1e-9.\n",
                 "| Condition | Gap | Comparator | ΔF1 [CI] | Holm p | Δdelay s [CI] | ΔFPR [CI] | Δchurn [CI] |",
                 "|---|---|---|---|---|---|---|---|"]
        for (cond, g, m), dd in h.groupby(["condition", "gap", "comparator"], sort=False):
            r = {x.metric: x for x in dd.itertuples()}
            f1 = r["persistence_f1"]
            lines.append(f"| {cond} | {g} | {_lab(cfg, m)} | {_ci(f1.mean_diff, f1.ci_lo, f1.ci_hi)} | {_f(f1.p_holm, 4)} | "
                         f"{_ci(r['delay_s'].mean_diff, r['delay_s'].ci_lo, r['delay_s'].ci_hi)} | "
                         f"{_ci(r['false_pers_mean'].mean_diff, r['false_pers_mean'].ci_lo, r['false_pers_mean'].ci_hi)} | "
                         f"{_ci(r['churn_mean'].mean_diff, r['churn_mean'].ci_lo, r['churn_mean'].ci_hi, 4)} |")
        (T / "h4_detail.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    lat = out / "aggregated" / "latency.csv"
    if lat.exists():
        L = pd.read_csv(lat)
        lines = [HDR, "# Temporal-module latency (ms per frame), N0_clean, budget-5 points, 8 synthetic edges, one machine\n",
                 "| Method | mean | median | p95 | p99 |", "|---|---|---|---|---|"]
        for _, r in L.iterrows():
            lines.append(f"| {_lab(cfg, r.method)} | {_f(r.latency_mean_ms, 4)} | {_f(r.latency_median_ms, 4)} | "
                         f"{_f(r.latency_p95_ms, 4)} | {_f(r.latency_p99_ms, 4)} |")
        (T / "latency.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
